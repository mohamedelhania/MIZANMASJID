type Key = keyof typeof dict.es;
type Val = string | readonly string[];

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => Val }>({
  lang: "es",
  setLang: () => {},
  t: (k) => dict.es[k] as Val,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("es");

  useEffect(() => {
    const saved = (typeof window !== "undefined" && localStorage.getItem("lang")) as Lang | null;
    if (saved === "es" || saved === "ar") setLangState(saved);
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    }
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("lang", l);
  };

  const t = (k: Key): Val => dict[lang][k] as Val;

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);

export function transliterateToArabic(text: string): string {
  const map: Record<string, string> = {
    'a': 'ا', 'b': 'ب', 't': 'ت', 'th': 'ث', 'j': 'ج', 'h': 'ح', 'kh': 'خ',
    'd': 'د', 'dh': 'ذ', 'r': 'ر', 'z': 'ز', 's': 'س', 'sh': 'ش',
    'f': 'ف', 'q': 'ق', 'k': 'ك', 'l': 'ل', 'm': 'م', 'n': 'ن', 'w': 'و', 'y': 'ي',
    'e': 'ي', 'i': 'ي', 'o': 'و', 'u': 'و', 'c': 'ك', 'p': 'ب', 'v': 'ف', 'g': 'غ'
  };
  let result = text.toLowerCase();
  ['th', 'kh', 'dh', 'sh'].forEach(c => {
    result = result.replace(new RegExp(c, 'g'), map[c]);
  });
  return result.split('').map(c => map[c] || c).join('');
}
